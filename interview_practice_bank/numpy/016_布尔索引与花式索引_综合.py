import numpy as np  # 导入 NumPy。
rows_ix, cols_ix = np.ix_([0, 2], [1, 3]); cross = np.arange(12).reshape(3, 4)[rows_ix, cols_ix]  # 使用ix_取得行列笛卡尔积。
assert cross.shape == (2, 2)  # 区分成对花式索引和网格索引。
