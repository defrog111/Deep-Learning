import re  # 导入正则表达式模块。
raw_pattern = r'\b\d+\b'; escaped_pattern = '\\b\\d+\\b'  # raw字符串避免正则反斜杠与Python转义叠加。
assert raw_pattern == escaped_pattern and re.findall(raw_pattern, 'a 12 b') == ['12']  # 验证两种字符串形式。
